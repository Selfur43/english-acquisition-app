}

enum ActivityKind { recall, choice, reading, rewrite, writing, simulation }

final class CurriculumActivity {
  const CurriculumActivity(
    this.id,
    this.title,
    this.skill,
    this.kind,
    this.prompt,
    this.answer,
    this.translation,
    this.explanation,
    this.model, {
    this.options = const [],
  });
  final String id, title, prompt, answer, translation, explanation, model;
  final LearningSkill skill;
  final ActivityKind kind;
  final List<String> options;
}

